function regionName(random: SeededRandom): string {
  const parts = random.int(2, 3);
  let name = '';
  for (let i = 0; i < parts; i += 1) {
    name += random.pick(SYLLABLES);
  }
  return name.charAt(0).toUpperCase() + name.slice(1);
}

/** Tries per region to find a center far enough from the others that labels do not collide. */
const PLACEMENT_ATTEMPTS = 40;

/** Elliptical regions with unique names, spread out so their labels stay readable. */
export function generateRegions(map: DemoMapSpec, random: SeededRandom): Region[] {
  const regions: Region[] = [];
  const used = new Set<string>();
  const margin = 280;
  const minDistance = Math.min(map.width, map.height) * 0.3;
  for (let i = 0; i < map.regionCount; i += 1) {
    let name = regionName(random);
    while (used.has(name)) {
      name = regionName(random);
    }
    used.add(name);
    let cx = 0;
    let cy = 0;
    for (let attempt = 0; attempt < PLACEMENT_ATTEMPTS; attempt += 1) {
      cx = random.range(margin, map.width - margin);
      cy = random.range(margin, map.height - margin);
      const crowded = regions.some(
        (other) => Math.hypot(other.cx - cx, other.cy - cy) < minDistance,
      );
      if (!crowded) {
        break;
      }
    }
    regions.push({
      name,
      cx,
      cy,
      rx: random.range(map.width * 0.07, map.width * 0.12),
      ry: random.range(map.height * 0.07, map.height * 0.12),
      color: map.regionColors[i % map.regionColors.length] ?? map.ground,
    });
  }
  return regions;
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

function markerAttributes(spec: LeafSpec, random: SeededRandom): NonNullable<Marker['attributes']> {
  switch (spec.kind) {
    case 'chest':
      return [
        { key: 'rarity', label: { en: 'Rarity', fr: 'Rareté' }, value: spec.name },
        { key: 'gold', label: { en: 'Gold', fr: 'Or' }, value: random.int(10, 500) },
        {
          key: 'locked',
          label: { en: 'Locked', fr: 'Verrouillé' },
          value: spec.id !== 'chest-common',
        },
      ];
    case 'relic':
      return [
        {
          key: 'era',
          label: { en: 'Era', fr: 'Époque' },
          value: random.pick(['First age', 'Second age', 'Age of ash']),
        },
        { key: 'level', label: { en: 'Level', fr: 'Niveau' }, value: random.int(1, 60) },
      ];
    case 'feather':
      return [
        {
          key: 'shade',
          label: { en: 'Shade', fr: 'Teinte' },
          value: random.pick(['Crimson', 'Azure', 'Ivory', 'Jade']),
        },
      ];
    case 'poi':
      return [];
  }
}

export interface DemoContentOptions {
  readonly markers?: number | undefined;
  readonly seed?: number | undefined;
}

export interface DemoContent {
  readonly manifest: Manifest;
  readonly categories: CategoryNodeData[];
  readonly markers: Record<string, Marker[]>;
  readonly articles: Readonly<Record<string, string>>;
  readonly regions: Readonly<Record<string, Region[]>>;
}

/** Splits `total` across maps by share; the last map takes the remainder. */
function markersPerMap(total: number): number[] {
  const counts = DEMO_MAPS.map((map) => Math.floor(total * map.share));
  const assigned = counts.reduce((sum, count) => sum + count, 0);
  counts[counts.length - 1] = (counts.at(-1) ?? 0) + (total - assigned);
  return counts;
}

export function buildDemoContent(options: DemoContentOptions = {}): DemoContent {
  const total = options.markers ?? DEFAULT_DEMO_MARKERS;
  const random = new SeededRandom(options.seed ?? DEFAULT_DEMO_SEED);
  const counts = markersPerMap(total);
  const regions: Record<string, Region[]> = {};
  const markers: Record<string, Marker[]> = {};

  DEMO_MAPS.forEach((map, mapIndex) => {
    const mapRegions = generateRegions(map, random);
    regions[map.id] = mapRegions;
    const list: Marker[] = [];
    const count = counts[mapIndex] ?? 0;
    for (let i = 0; i < count; i += 1) {
      const spec = random.weighted(ALL_LEAVES);
      const region = random.pick(mapRegions);
      const angle = random.range(0, Math.PI * 2);
      const distance = Math.sqrt(random.next()) * 1.4;
      const x = clamp(
        Math.round(region.cx + Math.cos(angle) * region.rx * distance),
        16,
        map.width - 16,
      );
      const y = clamp(
        Math.round(region.cy + Math.sin(angle) * region.ry * distance),
        16,
        map.height - 16,
      );
      const enName = typeof spec.name === 'string' ? spec.name : (spec.name.en ?? spec.id);
      const frName = typeof spec.name === 'string' ? spec.name : (spec.name.fr ?? enName);
      const marker: Marker = {
        id: `${map.id}-${String(i + 1).padStart(5, '0')}`,
        category: spec.id,
        position: { x, y },
        name: { en: `${enName} of ${region.name}`, fr: `${frName} de ${region.name}` },
        attributes: markerAttributes(spec, random),
        tags: [`region:${region.name.toLowerCase()}`],
      };
      if (random.next() < 0.3) {
        marker.description = {
          en: `Found near the ${random.pick(['north', 'south', 'east', 'west'])} edge of ${region.name}.`,
        };
      }
      if (spec.article !== undefined) {
        marker.article = spec.article;
      }
      list.push(marker);
    }
    markers[map.id] = list;
  });

  const manifest: Manifest = {
    formatVersion: CURRENT_FORMAT_VERSION,
    id: DEMO_PACK_ID,
    game: { name: 'Demo Realm', publisher: 'Fogline' },
    title: { en: 'Demo Realm - Procedural Atlas', fr: 'Demo Realm - Atlas procédural' },
    description: {
      en: 'A procedurally generated pack for trying Fogline. No game artwork or data.',
      fr: 'Un pack généré procéduralement pour essayer Fogline. Aucune ressource de jeu.',
    },
    version: '1.0.0',
    authors: [{ name: 'fogline-pack demo generator' }],
    license: {
      spdx: 'CC0-1.0',
      notes: 'Generated by fogline-pack demo. All imagery and names are procedural.',
    },
    attribution: ['Generated with fogline-pack'],
    defaultLanguage: 'en',
    theme: {
      palette: {
        accent: '#3fa7d6',
        background: '#101820',
        surface: '#18232e',
        text: '#e6edf3',
        mapBackdrop: '#0a1016',
      },
    },
    maps: DEMO_MAPS.map((map) => ({
      id: map.id,
      name: map.name,
      order: map.order,
      size: { width: map.width, height: map.height },
      tileSize: TILE_SIZE,
      minZoom: 0,
      maxZoom: nativeZoomFor({ width: map.width, height: map.height }, TILE_SIZE),
      tiles: { type: 'xyz', path: `maps/${map.id}/tiles` },
      thumbnail: `maps/${map.id}/thumbnail.webp`,
    })),
    categories: 'data/categories.json',
    markers: Object.fromEntries(DEMO_MAPS.map((map) => [map.id, `data/markers/${map.id}.json`])),
  };

  return { manifest, categories: DEMO_CATEGORIES, markers, articles: DEMO_ARTICLES, regions };
}
